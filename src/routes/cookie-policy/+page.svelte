    <h2>What are Cookies?</h2>
    <p>
      Cookies are small text files stored on a user&rsquo;s device when visiting
      a website or online platform.
    </p>
    <p>Cookies help websites and systems:</p>
    <ul>
      <li>Recognize users</li>
      <li>Maintain secure sessions</li>
      <li>Improve performance</li>
      <li>Remember preferences</li>
      <li>Support analytics and system functionality</li>
    </ul>
    <p>
      Cookies may be temporary (session cookies) or remain on a device for a
      specified period (persistent cookies).
    </p>

